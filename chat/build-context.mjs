/**
 * Builds the chat assistant's knowledge base from the site itself.
 *
 *   node chat/build-context.mjs
 *
 * Extracts readable text from each page and writes chat/context.txt. Because the
 * source is the site, the assistant cannot drift out of sync with what is
 * published — rebuild after editing any page and redeploy the worker.
 *
 * Excluded: the about-* layout prototypes (unpublished variants of one page),
 * and anything under tmp/ or Archive/.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SKIP = /^(about-cosmos|about-depth|about-paper|about-table|googlefa)/;

function pages() {
  const out = [];
  for (const f of readdirSync(ROOT)) {
    if (f.endsWith('.html') && !SKIP.test(f)) out.push(f);
  }
  for (const dir of ['work', 'research']) {
    if (!existsSync(join(ROOT, dir))) continue;
    for (const f of readdirSync(join(ROOT, dir))) {
      if (f.endsWith('.html')) out.push(`${dir}/${f}`);
    }
  }
  return out.sort();
}

function textOf(html) {
  return html
    .replace(/<(script|style|svg|canvas|noscript)\b[^>]*>[\s\S]*?<\/\1>/gi, ' ')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<\/(p|div|li|h[1-6]|section|tr|dd|dt|article)>/gi, '\n')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>').replace(/&quot;/g, '"')
    .replace(/&rsquo;|&#8217;/g, '’').replace(/&lsquo;/g, '‘')
    .replace(/&mdash;/g, '—').replace(/&ndash;/g, '–')
    .replace(/&middot;/g, '·').replace(/&eacute;/g, 'é')
    .replace(/&[a-z]+;|&#\d+;/gi, ' ')
    .replace(/[ \t]+/g, ' ')
    .replace(/\n\s*\n\s*\n+/g, '\n\n')
    .replace(/^[ \t]+/gm, '')
    .trim();
}

function titleOf(html, fallback) {
  const m = html.match(/<title>([^<]*)<\/title>/i);
  return m ? m[1].replace(/\s*[&·|]+\s*Priyal Shrivastava\s*$/i, '').trim() : fallback;
}

const parts = [];
let chars = 0;
for (const page of pages()) {
  const html = readFileSync(join(ROOT, page), 'utf8');
  const body = textOf(html);
  if (body.length < 400) continue;
  const url = page === 'index.html' ? '/' : '/' + page.replace(/\/index\.html$/, '/');
  parts.push(`### ${titleOf(html, page)}\nPage: ${url}\n\n${body}`);
  chars += body.length;
  console.log(`${page.padEnd(46)} ${String(body.length).padStart(6)} chars`);
}

const out = `# Priyal Shrivastava — site content
# Generated by chat/build-context.mjs. Do not edit by hand.
# Every claim the assistant makes must come from below.

${parts.join('\n\n---\n\n')}
`;
writeFileSync(join(ROOT, 'chat/context.txt'), out);
console.log('-'.repeat(54));
console.log(`${parts.length} pages, ${chars} chars (~${Math.round(chars / 4)} tokens) -> chat/context.txt`);

// Also emit the worker's knowledge module: the persona prompt with the site
// content appended. Generated as TypeScript so the worker needs no build-time
// text-module configuration.
const persona = readFileSync(join(ROOT, 'chat/system-prompt.md'), 'utf8');
const full = persona + '\n\n' + out;
writeFileSync(
  join(ROOT, 'chat/worker/src/knowledge.ts'),
  '// GENERATED by chat/build-context.mjs — do not edit.\n'
  + '// Rebuild after editing any page or chat/system-prompt.md.\n'
  + 'export const SYSTEM_PROMPT = ' + JSON.stringify(full) + ';\n'
);
console.log(`system prompt + content: ${full.length} chars (~${Math.round(full.length / 4)} tokens) -> chat/worker/src/knowledge.ts`);
